// Runs the Forge CLI's own client-side linters (scope usage, handlers, manifest, storage,
// CSP...) without `forge login`. Feature flags are stubbed "off", so server-side-only checks
// are skipped; `forge lint` after login stays authoritative for those.
//
// Scope coverage: Forge's permission linter only understands literal
// `requestJira(route`...`)` calls. Our REST calls go through small wrappers
// (src/jira/jira.ts, src/jira/confluence.ts), which hide the paths from it. So this script
// extracts every route`...` + HTTP method from those files and writes a temporary probe
// with direct calls, letting the linter verify each endpoint against manifest scopes.
//
//   node scripts/forge-lint-offline.cjs                      normal run
//   SELFTEST_EXPECT_ERRORS=1 node scripts/forge-lint-offline.cjs   proves the linter bites
const { execSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const cli = path.join(execSync('npm root -g').toString().trim(), '@forge/cli/node_modules');
const { lint, reportLintResults, problemCount } = require(path.join(cli, '@forge/lint'));
const YAML = require(path.join(cli, 'yaml'));

const root = path.resolve(__dirname, '..');
// The linter matches .ts files against tsconfig "include" relative to the CWD, so run from
// the app root with relative paths (absolute paths are silently skipped).
process.chdir(root);

const selftest = !!process.env.SELFTEST_EXPECT_ERRORS;
const manifest = YAML.parse(fs.readFileSync('manifest.yml', 'utf8'));
if (selftest) manifest.permissions.scopes = manifest.permissions.scopes.filter((s) => s !== 'write:jira-work' && s !== 'read:sprint:jira-software');

/* ---- build the endpoint probe ---- */
const PRODUCTS = { 'src/jira/jira.ts': 'requestJira', 'src/jira/confluence.ts': 'requestConfluence' };
const calls = [];
for (const [file, fn] of Object.entries(PRODUCTS)) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/route`([^`]+)`/g)) {
    const after = src.slice(m.index + m[0].length, m.index + m[0].length + 80);
    const method = after.match(/^[^)]*?method:\s*'([A-Z]+)'/)?.[1] ?? 'GET';
    // ${expr} -> sample value; the linter matches on the path shape.
    const pathLiteral = m[1].replace(/\$\{[^}]+\}/g, '1');
    calls.push({ fn, method, path: pathLiteral, from: file });
  }
}
const PROBE = path.join('src', '__scope_probe__.ts');
fs.writeFileSync(
  PROBE,
  `// AUTO-GENERATED by scripts/forge-lint-offline.cjs - deleted after the run.\nimport api, { route } from '@forge/api';\nexport const probe = async () => {\n` +
    calls.map((c) => `  await api.asUser().${c.fn}(route\`${c.path}\`, { method: '${c.method}' }); // ${c.from}`).join('\n') +
    `\n};\n`,
);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walk(p) : /\.(ts|tsx|js|jsx)$/.test(d.name) ? [p] : [];
  });
const files = walk('src');

const statsig = new Proxy({}, { get: () => async () => null }); // every flag "off"
const logger = { info: (...a) => console.log(...a), warn: (...a) => console.warn(...a), error: (...a) => console.error(...a), debug: () => {}, trace: () => {} };

lint(files, manifest, 'development', logger, statsig, { linter: { mode: 'client-side' } })
  .then((results) => {
    reportLintResults(logger, results, true);
    const { errors, warnings } = problemCount(results);
    console.log(`Checked ${calls.length} REST endpoint(s): ${[...new Set(calls.map((c) => `${c.method} ${c.path.split('?')[0]}`))].join(', ')}`);
    if (selftest) {
      console.log(errors ? `Self-test OK: linter reported ${errors} error(s) with scopes removed.` : 'Self-test FAILED: linter found nothing with scopes removed.');
      process.exitCode = errors ? 0 : 1;
      return;
    }
    console.log(`Forge lint (offline, client-side): ${errors} error(s), ${warnings} warning(s) across ${files.length - 1} source files.`);
    process.exitCode = errors ? 1 : 0;
  })
  .catch((e) => {
    console.error('Offline Forge lint could not run:', e.message);
    process.exitCode = 2;
  })
  .finally(() => fs.rmSync(PROBE, { force: true }));
